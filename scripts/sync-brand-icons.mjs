import { execFileSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { basename, join, resolve } from 'node:path';

const REPOSITORY = 'https://github.com/aegis-icons/aegis-icons.git';
const PRIMARY_PREFIX = 'icons/1_Primary/';

function slugify(value) {
  return value
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/&/g, ' and ')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

function parseSourceArgument() {
  const sourceArgument = process.argv.find((argument) => argument.startsWith('--source='));
  return sourceArgument ? resolve(sourceArgument.slice('--source='.length)) : null;
}

function cloneSource() {
  const directory = mkdtempSync(join(tmpdir(), 'aegis-icons-'));
  execFileSync('git', ['clone', '--depth', '1', REPOSITORY, directory], { stdio: 'inherit' });
  return directory;
}

const projectRoot = resolve(import.meta.dirname, '..');
const suppliedSource = parseSourceArgument();
const sourceRoot = suppliedSource ?? cloneSource();
const packPath = join(sourceRoot, 'pack.json');

if (!existsSync(packPath)) {
  throw new Error(`Aegis icon pack was not found at ${packPath}`);
}

const pack = JSON.parse(readFileSync(packPath, 'utf8'));
const sourceCommit = execFileSync('git', ['-C', sourceRoot, 'rev-parse', 'HEAD'], {
  encoding: 'utf8',
}).trim();
const outputDirectory = join(projectRoot, 'public', 'brand-icons', 'aegis');
const catalogPath = join(projectRoot, 'src', 'lib', 'brand-icon-catalog.generated.ts');
const usedIds = new Set();

rmSync(outputDirectory, { recursive: true, force: true });
mkdirSync(outputDirectory, { recursive: true });

const entries = pack.icons
  .filter((icon) => icon.filename.startsWith(PRIMARY_PREFIX))
  .map((icon) => {
    const baseId = slugify(icon.name) || 'brand';
    let id = baseId;
    let suffix = 2;

    while (usedIds.has(id)) {
      id = `${baseId}-${suffix}`;
      suffix += 1;
    }
    usedIds.add(id);

    const sourcePath = join(sourceRoot, icon.filename);
    const targetFilename = `${id}.svg`;
    cpSync(sourcePath, join(outputDirectory, targetFilename));

    const aliases = [...new Set([icon.name, ...(icon.issuer ?? [])])];
    return {
      id,
      name: icon.name,
      iconPath: `/brand-icons/aegis/${targetFilename}`,
      aliases,
    };
  })
  .sort((left, right) => left.name.localeCompare(right.name, 'en'));

const catalog = `// Generated by scripts/sync-brand-icons.mjs. Do not edit by hand.\n` +
  `export const BRAND_ICON_SOURCE = ${JSON.stringify({ repository: REPOSITORY, commit: sourceCommit, count: entries.length }, null, 2)} as const;\n\n` +
  `export const BRAND_ICON_CATALOG = ${JSON.stringify(entries, null, 2)} as const;\n`;

writeFileSync(catalogPath, catalog);

if (!suppliedSource) {
  rmSync(sourceRoot, { recursive: true, force: true });
}

console.log(`Synced ${entries.length} primary 2FA icons from ${basename(REPOSITORY)} at ${sourceCommit}.`);
