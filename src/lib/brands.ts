export interface BrandMeta extends BrandConfig {
  id: string;
}

export function getBrandMeta(issuerOrLabel?: string, label?: string): BrandMeta {
  const target = `${issuerOrLabel || ''} ${label || ''}`.toLowerCase();

  if (target.includes('google') || target.includes('gmail')) return { id: 'google', ...BRANDS.google };
  if (target.includes('github')) return { id: 'github', ...BRANDS.github };
  if (target.includes('discord')) return { id: 'discord', ...BRANDS.discord };
  if (target.includes('binance')) return { id: 'binance', ...BRANDS.binance };
  if (target.includes('telegram')) return { id: 'telegram', ...BRANDS.telegram };
  if (target.includes('epic') || target.includes('unreal')) return { id: 'epic', ...BRANDS.epic };
  if (target.includes('microsoft') || target.includes('xbox') || target.includes('outlook') || target.includes('live.com')) return { id: 'microsoft', ...BRANDS.microsoft };
  if (target.includes('twitch')) return { id: 'twitch', ...BRANDS.twitch };
  if (target.includes('vk') || target.includes('vkontakte')) return { id: 'vk', ...BRANDS.vk };
  if (target.includes('steam') || target.includes('valve')) return { id: 'steam', ...BRANDS.steam };
  if (target.includes('blizzard') || target.includes('battle.net')) return { id: 'blizzard', ...BRANDS.blizzard };
  if (target.includes('reddit')) return { id: 'reddit', ...BRANDS.reddit };

  return {
    id: 'default',
    name: '2FA',
    color: '#66C0F4',
    bgColor: 'rgba(102, 192, 244, 0.15)',
    iconPath: '',
  };
}

export function getBrandConfig(issuer?: string, label?: string): BrandConfig | null {
  const meta = getBrandMeta(issuer, label);
  return meta.id === 'default' ? null : meta;
}
